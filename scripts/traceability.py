"""Build docs/traceability.md: URS requirement → tests → latest result. Run after `pytest`.

A requirement with no test, or with a failing test, is shown as not verified: that is the point of the matrix.
"""

import json
import re
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def main() -> None:
    urs = re.findall(r"^\| (URS-\d+) \| (.+?) \| ([HML]) \|$", (ROOT / "docs" / "URS.md").read_text(), re.M)
    ev = json.loads((ROOT / "reports" / "test_evidence.json").read_text())
    by_req = defaultdict(list)
    for e in ev:
        for r in e["requirements"]:
            by_req[r].append(e)
    lines = ["# Traceability matrix", "", "Generated by `scripts/traceability.py` from the latest `pytest` run.", "",
             "| Requirement | Risk | Verified by | Result |", "|---|---|---|---|"]  # fmt: skip
    for rid, text, risk in urs:
        tests = by_req.get(rid, [])
        ok = bool(tests) and all(t["outcome"] == "passed" for t in tests)
        names = "<br>".join(f"`{t['test'].split('::')[-1]}`" for t in tests) or "—"
        lines.append(f"| {rid}: {text[:70]}{'…' if len(text) > 70 else ''} | {risk} | {names} | "
                     f"{'✅ pass' if ok else '❌ not verified'} |")  # fmt: skip
    n_ok = sum(1 for rid, _, _ in urs if by_req.get(rid) and all(t["outcome"] == "passed" for t in by_req[rid]))
    lines += ["", f"**{n_ok} / {len(urs)} requirements verified.**", ""]
    (ROOT / "docs" / "traceability.md").write_text("\n".join(lines))
    print(f"{n_ok}/{len(urs)} requirements verified → docs/traceability.md")


if __name__ == "__main__":
    main()
